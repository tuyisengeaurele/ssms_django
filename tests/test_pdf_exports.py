"""The system report and the audit log as PDF documents with the shared letterhead."""
import io
import re
from decimal import Decimal

import pytest
from pypdf import PdfReader

from audit_log.models import AuditLog
from tests.factories import BatchFactory, FarmFactory, HarvestRecordFactory, UserFactory

pytestmark = pytest.mark.django_db

REPORT = '/api/admin/reports?export=pdf'
AUDIT = '/api/admin/audit-log?export=pdf'


@pytest.fixture
def admin():
    return UserFactory(role='ADMIN', name='Aline Uwase')


def text_of(response):
    assert response.status_code == 200
    reader = PdfReader(io.BytesIO(response.content))
    return '\n'.join(page.extract_text() for page in reader.pages)


def pages_of(response):
    return len(PdfReader(io.BytesIO(response.content)).pages)


def entry(**over):
    fields = dict(user_email='serge@example.rw', user_name='Mugisha Serge', action='CREATE', resource='Batch', resource_id='b1', detail='Started a batch')
    fields.update(over)
    return AuditLog.objects.create(**fields)


# ── the system report ───────────────────────────────────────────────────────

def test_the_report_comes_as_a_pdf_with_a_dated_file_name(auth_client, admin):
    response = auth_client(admin).get(REPORT)
    assert response.status_code == 200
    assert response['Content-Type'] == 'application/pdf'
    assert response.content.startswith(b'%PDF-')
    assert re.fullmatch(r'attachment; filename="ssms_report_\d{4}-\d{2}-\d{2}\.pdf"', response['Content-Disposition'])


def test_the_report_carries_the_letterhead_and_the_name_of_the_person_who_asked(auth_client, admin):
    text = text_of(auth_client(admin).get(REPORT))
    assert 'System report' in text
    assert 'Smart Sericulture Management System' in text
    assert 'Generated by Aline Uwase' in text
    assert 'smartsericulturerw@gmail.com' in text


def test_the_report_has_the_same_numbers_as_the_screen(auth_client, admin):
    batch = BatchFactory(farm=FarmFactory(owner=UserFactory(role='FARMER', name='Mugisha Serge')), stage='HARVEST')
    HarvestRecordFactory(batch=batch, cocoon_weight_kg=Decimal('12.5'), quality_grade='A')
    client = auth_client(admin)
    data = client.get('/api/admin/reports').json()['data']
    text = text_of(client.get(REPORT))
    assert str(data['harvests']['totalKg']) in text
    assert 'Mugisha Serge' in text
    assert 'Grade A' in text or re.search(r'\bA\b', text)
    assert str(data['users']['total']) in text


def test_the_report_names_its_sections(auth_client, admin):
    text = text_of(auth_client(admin).get(REPORT))
    for heading in ('Users', 'Batches by stage', 'Harvests', 'Disease checks', 'Activity in the last 30 days', 'Farmers with the most farms'):
        assert heading in text


@pytest.mark.parametrize('role', ['FARMER', 'SUPERVISOR'])
def test_only_an_admin_gets_the_report_pdf(auth_client, role):
    assert auth_client(UserFactory(role=role)).get(REPORT).status_code == 403


def test_a_stranger_gets_nothing(api_client):
    assert api_client.get(REPORT).status_code == 401


def test_the_csv_report_is_still_there(auth_client, admin):
    response = auth_client(admin).get('/api/admin/reports?export=csv')
    assert response['Content-Type'].startswith('text/csv')


# ── the audit log ───────────────────────────────────────────────────────────

def test_the_audit_log_comes_as_a_pdf_with_a_dated_file_name(auth_client, admin):
    entry()
    response = auth_client(admin).get(AUDIT)
    assert response['Content-Type'] == 'application/pdf'
    assert re.fullmatch(r'attachment; filename="audit_log_\d{4}-\d{2}-\d{2}\.pdf"', response['Content-Disposition'])


def test_the_audit_log_pdf_lists_the_entries_under_the_letterhead(auth_client, admin):
    entry(detail='Started a batch')
    text = text_of(auth_client(admin).get(AUDIT))
    assert 'Audit log' in text
    assert 'Generated by Aline Uwase' in text
    assert 'Mugisha Serge' in text and 'Started a batch' in text and 'Batch' in text


def test_the_audit_log_pdf_keeps_the_filters_the_screen_had(auth_client, admin):
    entry(action='LOGIN', resource='Session', detail='Signed in')
    entry(action='DELETE', resource='Farm', detail='Removed a farm')
    client = auth_client(admin)
    text = text_of(client.get(f'{AUDIT}&action=DELETE'))
    assert 'Removed a farm' in text
    assert 'Signed in' not in text
    assert 'Action: DELETE' in text


def test_a_search_is_kept_and_named(auth_client, admin):
    entry(detail='Moved to the east house')
    entry(detail='Something else')
    text = text_of(auth_client(admin).get(f'{AUDIT}&search=east'))
    assert 'east house' in text and 'Something else' not in text
    assert 'Search: east' in text


def test_with_no_filter_the_document_says_so(auth_client, admin):
    entry()
    assert 'No filters' in text_of(auth_client(admin).get(AUDIT))


def test_a_long_log_is_cut_at_the_limit_and_says_how_many_were_left_out(auth_client, admin, settings):
    settings.PDF_AUDIT_ROW_LIMIT = 5
    for i in range(8):
        entry(detail=f'Entry number {i}')
    text = text_of(auth_client(admin).get(AUDIT))
    assert 'Showing the latest 5 of 8 entries.' in text
    assert 'Entry number 7' in text and 'Entry number 0' not in text
    assert 'Use the CSV export for the full list.' in text


def test_a_log_within_the_limit_has_no_cut_notice(auth_client, admin):
    entry()
    entry()
    text = text_of(auth_client(admin).get(AUDIT))
    assert '2 entries.' in text
    assert 'Showing the latest' not in text


def test_an_empty_log_still_makes_a_document(auth_client, admin):
    AuditLog.objects.all().delete()
    assert 'No entries match.' in text_of(auth_client(admin).get(AUDIT))


def test_a_log_that_runs_over_a_page_is_numbered(auth_client, admin):
    for i in range(120):
        entry(detail=f'Entry {i}')
    response = auth_client(admin).get(AUDIT)
    total = pages_of(response)
    assert total >= 2
    assert f'Page 1 of {total}' in text_of(response)


def test_markup_in_a_detail_is_shown_as_text(auth_client, admin):
    entry(detail='<b>bold</b> & <script>x</script>')
    assert '<b>bold</b> & <script>x</script>' in text_of(auth_client(admin).get(AUDIT))


@pytest.mark.parametrize('role', ['FARMER', 'SUPERVISOR'])
def test_only_an_admin_gets_the_audit_pdf(auth_client, role):
    assert auth_client(UserFactory(role=role)).get(AUDIT).status_code == 403


def test_the_audit_csv_is_still_there(auth_client, admin):
    entry()
    response = auth_client(admin).get('/api/admin/audit-log?export=csv')
    assert response['Content-Type'] == 'text/csv'
