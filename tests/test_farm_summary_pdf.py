# ── who may ask ─────────────────────────────────────────────────────────────

def test_a_supervisor_of_the_cooperative_may_ask(auth_client):
    coop = CooperativeFactory()
    farm = FarmFactory(owner=UserFactory(role='FARMER', cooperative=coop, name='Mugisha Serge'))
    supervisor = UserFactory(role='SUPERVISOR', cooperative=coop, name='Claire Mukamana')
    assert 'Generated by Claire Mukamana' in text_of(summary(auth_client(supervisor), farm))


def test_an_admin_may_ask(auth_client, farm):
    assert 'Generated by Aline Uwase' in text_of(summary(auth_client(UserFactory(role='ADMIN', name='Aline Uwase')), farm))


def test_someone_elses_farm_is_not_found(auth_client, farm):
    assert summary(auth_client(UserFactory(role='FARMER')), farm).status_code == 404


def test_a_deleted_farm_is_not_found(auth_client, owner, farm):
    farm.is_active = False
    farm.save(update_fields=['is_active'])
    assert summary(auth_client(owner), farm).status_code == 404


def test_a_stranger_gets_nothing(api_client, farm):
    assert api_client.get(f'/api/farms/{farm.pk}/summary').status_code == 401
