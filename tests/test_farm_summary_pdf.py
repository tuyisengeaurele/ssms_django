"""The farm summary as a PDF on the SSMS letterhead, in the language the person reads."""
import io
import re
from decimal import Decimal

import pytest
from pypdf import PdfReader

from batches.placement import place_batch
from farms.models import RearingRoom
from tests.factories import (
    AlertLogFactory,
    BatchFactory,
    CooperativeFactory,
    FarmFactory,
    HarvestRecordFactory,
    UserFactory,
)

pytestmark = pytest.mark.django_db


@pytest.fixture
def owner():
    return UserFactory(role='FARMER', name='Mugisha Serge')


@pytest.fixture
def farm(owner):
    return FarmFactory(owner=owner, name='Serge Farm', location='KG 9 Ave, Kabeza, Gatsibo, Eastern Province')


def summary(client, farm, lang=None):
    query = f'?lang={lang}' if lang else ''
    return client.get(f'/api/farms/{farm.pk}/summary{query}')


def text_of(response):
    assert response.status_code == 200, response.content[:200]
    return '\n'.join(page.extract_text() for page in PdfReader(io.BytesIO(response.content)).pages)


def code(batch):
    return batch.pk[-8:].upper()


# ── the document ────────────────────────────────────────────────────────────

def test_the_summary_is_a_pdf_with_a_file_name_that_names_the_farm(auth_client, owner, farm):
    response = summary(auth_client(owner), farm)
    assert response['Content-Type'] == 'application/pdf'
    assert response.content.startswith(b'%PDF-')
    assert re.fullmatch(rf'attachment; filename="farm_summary_{farm.pk[-8:].upper()}_\d{{4}}-\d{{2}}-\d{{2}}\.pdf"', response['Content-Disposition'])


def test_it_is_on_the_letterhead_and_names_the_farm_and_who_asked(auth_client, owner, farm):
    text = text_of(summary(auth_client(owner), farm))
    assert 'Farm summary' in text
    assert 'Smart Sericulture Management System' in text
    assert 'Serge Farm' in text
    assert 'Generated by Mugisha Serge' in text


def test_the_farm_facts_are_shown(auth_client, owner, farm):
    text = text_of(summary(auth_client(owner), farm))
    for expected in ('KG 9 Ave, Kabeza, Gatsibo, Eastern Province', 'Mugisha Serge', 'Owner', 'Place', 'Registered'):
        assert expected in text


# ── rooms ───────────────────────────────────────────────────────────────────

def test_rooms_are_listed_with_the_batches_in_them_now(auth_client, owner, farm):
    first = RearingRoom.objects.create(farm=farm, name='Rearing house 1')
    RearingRoom.objects.create(farm=farm, name='Rearing house 2')
    place_batch(BatchFactory(farm=farm, stage='LARVA'), first)
    place_batch(BatchFactory(farm=farm, stage='PUPA'), first)
    text = text_of(summary(auth_client(owner), farm))
    assert re.search(r'Rearing house 1\s+2', text)
    assert re.search(r'Rearing house 2\s+0', text)


def test_a_deleted_room_is_left_out(auth_client, owner, farm):
    RearingRoom.objects.create(farm=farm, name='Old shed', is_active=False)
    assert 'Old shed' not in text_of(summary(auth_client(owner), farm))


def test_a_farm_without_rooms_says_so(auth_client, owner, farm):
    assert 'No rooms yet.' in text_of(summary(auth_client(owner), farm))


# ── batches ─────────────────────────────────────────────────────────────────

def test_the_batches_are_listed_with_stage_and_dates(auth_client, owner, farm):
    room = RearingRoom.objects.create(farm=farm, name='Rearing house 1')
    batch = BatchFactory(farm=farm, stage='LARVA', quantity=3, quantity_unit='BOXES')
    place_batch(batch, room)
    text = text_of(summary(auth_client(owner), farm))
    assert f'#{code(batch)}' in text
    assert 'Larva' in text
    assert '3 egg boxes' in text
    assert re.search(rf'#{code(batch)}.*Larva', text, re.S)


def test_a_deleted_batch_is_left_out(auth_client, owner, farm):
    gone = BatchFactory(farm=farm, is_active=False)
    assert f'#{code(gone)}' not in text_of(summary(auth_client(owner), farm))


def test_another_farms_batch_is_left_out(auth_client, owner, farm):
    other = BatchFactory(farm=FarmFactory(owner=owner, name='River Farm'))
    assert f'#{code(other)}' not in text_of(summary(auth_client(owner), farm))


def test_a_farm_without_batches_says_so(auth_client, owner, farm):
    assert 'No batches yet.' in text_of(summary(auth_client(owner), farm))


def test_a_farm_with_many_batches_runs_over_pages_and_numbers_them(auth_client, owner, farm):
    for _ in range(70):
        BatchFactory(farm=farm)
    response = summary(auth_client(owner), farm)
    pages = PdfReader(io.BytesIO(response.content)).pages
    assert len(pages) >= 2
    assert f'Page 1 of {len(pages)}' in pages[0].extract_text()


# ── harvest and alerts ──────────────────────────────────────────────────────

def test_the_harvest_of_every_batch_of_the_farm_is_summed(auth_client, owner, farm):
    one = BatchFactory(farm=farm, stage='HARVEST')
    two = BatchFactory(farm=farm, stage='HARVEST')
    HarvestRecordFactory(batch=one, cocoon_weight_kg=Decimal('12.5'), silk_yield_g=Decimal('900'), quality_grade='A')
    HarvestRecordFactory(batch=two, cocoon_weight_kg=Decimal('4'), quality_grade='B')
    HarvestRecordFactory(batch=two, cocoon_weight_kg=Decimal('99'), quality_grade='C', is_active=False)
    text = text_of(summary(auth_client(owner), farm))
    assert '2 records, 16.5 kg of cocoons, 900 g of silk.' in text
    assert 'Grade A: 1, Grade B: 1, Grade C: 0' in text


def test_the_harvest_of_a_deleted_batch_is_not_counted(auth_client, owner, farm):
    gone = BatchFactory(farm=farm, stage='HARVEST', is_active=False)
    HarvestRecordFactory(batch=gone, cocoon_weight_kg=Decimal('50'))
    assert 'No harvest recorded.' in text_of(summary(auth_client(owner), farm))


def test_unseen_alerts_of_batches_and_rooms_are_counted(auth_client, owner, farm):
    room = RearingRoom.objects.create(farm=farm, name='Rearing house 1')
    batch = BatchFactory(farm=farm)
    AlertLogFactory(batch=batch, type='DISEASE', message='x', is_read=False)
    AlertLogFactory(batch=None, room=room, type='TEMPERATURE', message='y', is_read=False)
    AlertLogFactory(batch=batch, type='DISEASE', message='z', is_read=True)
    other = BatchFactory(farm=FarmFactory(owner=owner, name='River Farm'))
    AlertLogFactory(batch=other, type='DISEASE', message='w', is_read=False)
    assert '2 alerts not yet seen.' in text_of(summary(auth_client(owner), farm))


def test_no_alerts_says_so(auth_client, owner, farm):
    assert 'No alerts waiting.' in text_of(summary(auth_client(owner), farm))


