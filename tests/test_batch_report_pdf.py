# ── the conditions summary on its own ───────────────────────────────────────

RANGE = {'temp_min': 22.0, 'temp_max': 28.0, 'hum_min': 70.0, 'hum_max': 85.0}


def point(temperature, humidity, count=1):
    return {'timestamp': '2026-10-01T00:00:00+00:00', 'temperature': temperature, 'humidity': humidity, 'count': count}


def test_an_empty_series_sums_up_to_nothing():
    from batches.report import summarise_conditions
    assert summarise_conditions([], 6, RANGE) is None


def test_the_hours_are_the_real_length_of_the_buckets():
    from batches.report import summarise_conditions
    assert summarise_conditions([point(25, 78), point(26, 78)], 6, RANGE)['hours'] == 12
    assert summarise_conditions([point(25, 78), point(26, 78)], 1, RANGE)['hours'] == 2


def test_a_bucket_with_more_readings_counts_for_more():
    from batches.report import summarise_conditions
    result = summarise_conditions([point(20, 70, count=3), point(30, 90, count=1)], 1, RANGE)
    assert result['temp_avg'] == 22.5 and result['hum_avg'] == 75.0
    assert (result['temp_min'], result['temp_max']) == (20, 30)


def test_a_bucket_that_reports_no_count_still_counts_once():
    from batches.report import summarise_conditions
    assert summarise_conditions([point(20, 70, count=0), point(30, 90, count=0)], 1, RANGE)['temp_avg'] == 25.0


def test_halves_round_up_like_the_screen():
    from batches.report import summarise_conditions
    assert summarise_conditions([point(22.2, 70), point(22.3, 70)], 1, RANGE)['temp_avg'] == 22.3


def test_the_share_inside_the_range_counts_both_temperature_and_humidity():
    from batches.report import summarise_conditions
    points = [point(25, 78), point(25, 95), point(31, 78), point(25, 78)]
    assert summarise_conditions(points, 1, RANGE)['in_range_pct'] == 50
