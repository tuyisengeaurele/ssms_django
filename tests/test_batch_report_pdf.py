def report(client, batch, lang=None):
    query = f'?lang={lang}' if lang else ''
    return client.get(f'/api/batches/{batch.pk}/report{query}')


def text_of(response):
    assert response.status_code == 200, response.content[:200]
    return '\n'.join(page.extract_text() for page in PdfReader(io.BytesIO(response.content)).pages)


def code(batch):
    return batch.pk[-8:].upper()


def reading(batch, temperature, humidity, hours_ago):
    row = SensorReadingFactory(batch=batch, temperature=temperature, humidity=humidity)
    SensorReading.objects.filter(pk=row.pk).update(timestamp=timezone.now() - timedelta(hours=hours_ago))


# ── the document ────────────────────────────────────────────────────────────

def test_the_report_is_a_pdf_with_a_file_name_that_names_the_batch(auth_client, owner, batch):
    response = report(auth_client(owner), batch)
    assert response['Content-Type'] == 'application/pdf'
    assert response.content.startswith(b'%PDF-')
    assert re.fullmatch(rf'attachment; filename="batch_report_{code(batch)}_\d{{4}}-\d{{2}}-\d{{2}}\.pdf"', response['Content-Disposition'])


def test_the_report_is_on_the_letterhead_and_names_who_asked(auth_client, owner, batch):
    text = text_of(report(auth_client(owner), batch))
    assert 'Batch report' in text
    assert 'Smart Sericulture Management System' in text
    assert 'Generated by Mugisha Serge' in text
    assert f'Batch #{code(batch)} on Serge Farm' in text


def test_the_batch_facts_are_shown(auth_client, owner, batch):
    text = text_of(report(auth_client(owner), batch))
    for expected in ('Pupa', 'Serge Farm', 'KG 9 Ave, Kabeza, Gatsibo, Eastern Province', 'Bivoltine', '3 egg boxes', 'Second cycle of the year'):
        assert expected in text


def test_the_day_of_the_cycle_is_shown(auth_client, owner, batch):
    assert re.search(r'Day \d+ of \d+\. Harvest is expected on \d+ [A-Z][a-z]+ \d{4}\.', text_of(report(auth_client(owner), batch)))


def test_a_harvested_batch_has_no_day_line(auth_client, owner, farm):
    done = BatchFactory(farm=farm, stage='HARVEST')
    assert 'Harvest is expected on' not in text_of(report(auth_client(owner), done))


