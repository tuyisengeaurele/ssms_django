# ── conditions ──────────────────────────────────────────────────────────────

def test_conditions_are_lowest_average_and_highest(auth_client, owner, batch):
    reading(batch, 20.0, 70.0, 20)
    reading(batch, 30.0, 90.0, 8)
    text = text_of(report(auth_client(owner), batch))
    assert 'Temperature: lowest 20 °C, average 25 °C, highest 30 °C' in text
    assert 'Humidity: lowest 70 %, average 80 %, highest 90 %' in text


def test_the_share_of_hours_inside_the_range_uses_the_range_for_the_stage(auth_client, owner, batch):
    StageThreshold.objects.filter(stage='PUPA').update(temp_min=23.0, temp_max=27.0, hum_min=72.0, hum_max=82.0)
    # Twelve hours apart, so they fall in two different six hour buckets.
    reading(batch, 25.0, 78.0, 20)
    reading(batch, 30.0, 78.0, 8)
    text = text_of(report(auth_client(owner), batch))
    assert '50 % of the 12 hours were inside the usual range for the Pupa stage (23 to 27 °C, 72 to 82 %).' in text


def test_a_batch_with_no_readings_says_so(auth_client, owner, batch):
    assert 'No readings in the last 30 days.' in text_of(report(auth_client(owner), batch))


def test_readings_older_than_thirty_days_are_left_out(auth_client, owner, batch):
    reading(batch, 40.0, 99.0, 24 * 40)
    assert 'No readings in the last 30 days.' in text_of(report(auth_client(owner), batch))


# ── deaths, checks, alerts, harvest ─────────────────────────────────────────

def test_deaths_are_totalled_against_the_start_when_counted_in_worms(auth_client, owner, farm):
    worms = BatchFactory(farm=farm, stage='LARVA', quantity=200, quantity_unit='WORMS')
    MortalityRecord.objects.create(batch=worms, count=10, recorded_on=date(2026, 10, 1), note='Heat')
    MortalityRecord.objects.create(batch=worms, count=5, recorded_on=date(2026, 10, 2), note='')
    text = text_of(report(auth_client(owner), worms))
    assert 'Total: 15 of 200 worms (7.5 %)' in text
    assert 'Heat' in text


def test_a_deleted_death_entry_is_not_counted(auth_client, owner, batch):
    MortalityRecord.objects.create(batch=batch, count=9, recorded_on=date(2026, 10, 1), is_active=False)
    assert 'No deaths recorded.' in text_of(report(auth_client(owner), batch))


def test_every_death_entry_is_listed_even_a_long_log(auth_client, owner, batch):
    for day in range(1, 21):
        MortalityRecord.objects.create(batch=batch, count=day, recorded_on=date(2026, 9, day), note=f'Note {day}')
    text = text_of(report(auth_client(owner), batch))
    assert 'Note 1' in text and 'Note 20' in text


