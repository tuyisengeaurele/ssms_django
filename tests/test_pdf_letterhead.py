"""The letterhead every formal PDF shares: logo, title, date, who made it, page numbers and the footer."""
import io
import re

import pytest
from pypdf import PdfReader

from core.pdf import build_pdf, data_table, facts_table, heading, para

pytestmark = pytest.mark.django_db


def read(pdf):
    return PdfReader(io.BytesIO(pdf))


def page_texts(pdf):
    return [page.extract_text() for page in read(pdf).pages]


def one_page(*story, **over):
    kwargs = dict(title='System report', generated_by='Aline Uwase')
    kwargs.update(over)
    return build_pdf(kwargs.pop('title'), list(story), **kwargs)


def long_story(lines=120):
    return [para(f'Line {i} of a long document.') for i in range(lines)]


# ── a real PDF ──────────────────────────────────────────────────────────────

def test_the_result_is_a_pdf():
    pdf = one_page(para('Hello'))
    assert isinstance(pdf, bytes)
    assert pdf.startswith(b'%PDF-')


def test_the_page_is_a4():
    box = read(one_page(para('Hello'))).pages[0].mediabox
    assert (round(float(box.width)), round(float(box.height))) == (595, 842)


# ── the letterhead ──────────────────────────────────────────────────────────

def test_every_page_has_the_name_the_title_and_the_footer(settings):
    settings.ORG_ADDRESS = 'UR-CST, P.O. Box 3900, Kigali, Rwanda'
    settings.SUPPORT_EMAIL = 'help@ssms.example'
    settings.FRONTEND_URL = 'https://ssms.example'
    texts = page_texts(build_pdf('Audit log', long_story(), generated_by='Aline Uwase'))
    assert len(texts) >= 2
    for text in texts:
        assert 'Smart Sericulture Management System' in text
        assert 'Audit log' in text
        assert 'UR-CST, P.O. Box 3900, Kigali, Rwanda' in text
        assert 'help@ssms.example' in text
        assert 'https://ssms.example' in text


def test_pages_are_numbered_out_of_the_total():
    texts = page_texts(build_pdf('Audit log', long_story(), generated_by='Aline Uwase'))
    total = len(texts)
    assert total >= 2
    for number, text in enumerate(texts, start=1):
        assert f'Page {number} of {total}' in text


def test_a_short_document_says_page_1_of_1():
    assert 'Page 1 of 1' in page_texts(one_page(para('Hello')))[0]


def test_the_logo_is_on_the_page():
    assert len(read(one_page(para('Hello'))).pages[0].images) >= 1


def test_the_date_and_who_made_the_document_are_on_every_page():
    texts = page_texts(build_pdf('Audit log', long_story(), generated_by='Aline Uwase'))
    for text in texts:
        assert 'Generated by Aline Uwase' in text
        assert re.search(r'\d{1,2} [A-Z][a-z]+ \d{4}, \d{2}:\d{2} UTC', text)


def test_the_title_opens_the_first_page_and_a_subtitle_follows_it():
    text = page_texts(one_page(para('Body'), subtitle='Last 30 days'))[0]
    assert 'Last 30 days' in text


def test_no_dash_characters_that_the_project_bans_appear():
    text = ''.join(page_texts(one_page(para('Hello'))))
    assert chr(8212) not in text and chr(8211) not in text


# ── content helpers ─────────────────────────────────────────────────────────

def test_a_table_shows_its_header_and_rows():
    text = page_texts(one_page(data_table(['Stage', 'Batches'], [['Egg', 3], ['Larva', 5]])))[0]
    for word in ('Stage', 'Batches', 'Egg', 'Larva'):
        assert word in text


def test_a_table_that_runs_over_a_page_repeats_its_header():
    rows = [[f'Row {i}', i] for i in range(150)]
    texts = page_texts(build_pdf('Rows', [data_table(['Name', 'Count'], rows)], generated_by='Aline Uwase'))
    assert len(texts) >= 2
    assert all('Name' in text for text in texts)


def test_facts_show_label_and_value():
    text = page_texts(one_page(facts_table([('Total users', 12), ('Farms', 4)])))[0]
    assert 'Total users' in text and '12' in text and 'Farms' in text


def test_a_heading_is_shown():
    assert 'Users by role' in page_texts(one_page(heading('Users by role')))[0]


def test_an_empty_table_says_so_instead_of_drawing_a_bare_header():
    text = page_texts(one_page(data_table(['Name', 'Count'], [], empty='Nothing to show.')))[0]
    assert 'Nothing to show.' in text


# ── text that is not ours ───────────────────────────────────────────────────

def test_markup_in_a_name_is_shown_as_text_and_does_not_break_the_page():
    text = page_texts(one_page(para('<b>Tom</b> & <script>x</script>'), data_table(['Name'], [['<i>Tom</i> & Co']])))[0]
    assert '<b>Tom</b> & <script>x</script>' in text
    assert '<i>Tom</i> & Co' in text


def test_french_letters_and_the_apostrophe_are_kept():
    text = page_texts(one_page(para('Évaluation réalisée à Gatsibo, côté ouest. N’umudugudu')))[0]
    assert 'Évaluation réalisée à Gatsibo, côté ouest.' in text


def test_a_letter_the_page_font_cannot_draw_does_not_stop_the_document():
    pdf = one_page(para('Name: ŵẋ'))
    assert pdf.startswith(b'%PDF-')


def test_a_very_long_word_does_not_stop_the_document():
    pdf = one_page(data_table(['Detail'], [['x' * 400]]))
    assert pdf.startswith(b'%PDF-')


def test_the_name_of_whoever_made_it_may_hold_markup_too():
    text = page_texts(build_pdf('Report', [para('Body')], generated_by='<b>Aline</b> & Co'))[0]
    assert 'Generated by <b>Aline</b> & Co' in text
